export function useT(lang: Lang) {
  function get<S extends keyof typeof t, K extends keyof (typeof t)[S]>(
    section: S,
    key: K,
  ): string {
    const entry = t[section][key] as Record<Lang, string>;
    return entry[lang] || entry["de"];
  }
  return get;
}

export function getOrderStatus(status: string, lang: Lang, isSupplier = false): string {
  const section = isSupplier ? t.orderStatusSupplier : t.orderStatus;
  const entry = section[status as keyof typeof section];
  if (!entry) return status;
  return entry[lang];
}

export function getComplaintStatus(status: string, lang: Lang): string {
  const entry = t.complaintStatus[status as keyof typeof t.complaintStatus];
  if (!entry) return status;
  return entry[lang];
}

export function getWeekdayLabel(dayValue: number, lang: Lang): string {
  const map: Record<number, keyof typeof t.weekdays> = {
    1: "monday", 2: "tuesday", 3: "wednesday", 4: "thursday",
    5: "friday", 6: "saturday", 0: "sunday",
  };
  const key = map[dayValue];
  if (!key) return "";
  return t.weekdays[key][lang];
}

export function getWeekdays(lang: Lang) {
  return [
    { value: 1, label: t.weekdays.monday[lang] },
    { value: 2, label: t.weekdays.tuesday[lang] },
    { value: 3, label: t.weekdays.wednesday[lang] },
    { value: 4, label: t.weekdays.thursday[lang] },
    { value: 5, label: t.weekdays.friday[lang] },
    { value: 6, label: t.weekdays.saturday[lang] },
    { value: 0, label: t.weekdays.sunday[lang] },
  ];
}

export function getDateLocale(lang: Lang) {
  return lang === "it" ? "it" : "de";
}

